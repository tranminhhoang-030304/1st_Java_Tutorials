package javacorebasic.chapter2_oop.a_classandobject;

public class chapter2a_ClassStudent {
    // Thuộc tính (Properties/Attributes) - Đặc điểm của sinh viên
    String name;
    int age;

    // Phương thức (Methods) - Hành động của sinh viên
    public void study() {
        System.out.println(name + " đang học lập trình Java.");
    }
}
//Class (Lớp): 1 class có Thuộc tính/Tính chất và có Phương thức/Hành động.
//Object (Đối tượng): Là 1 đối tượng cụ thể trong class được viết theo Thuộc tính/Tính chất của class